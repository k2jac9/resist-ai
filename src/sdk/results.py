"""Pipeline results container for the ResistAI SDK.

Collects outputs from each pipeline step into a single, navigable object
with typed accessors and export helpers.
"""
from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional

logger = logging.getLogger(__name__)


@dataclass
class ScreeningHit:
    """A single drug-target screening result."""

    drug_name: str = ""
    smiles: str = ""
    confidence: float = 0.0
    ptm_score: float = 0.0
    iptm_score: float = 0.0
    ligand_iptm: float = 0.0
    structure_cif: str = ""
    raw: dict = field(default_factory=dict)


@dataclass
class DockingPose:
    """A single docking pose from DiffDock."""

    ligand_sdf: str = ""
    confidence: float = 0.0
    drug_name: str = ""
    smiles: str = ""


@dataclass
class NovelMolecule:
    """A molecule generated by MolMIM."""

    smiles: str = ""
    score: float = 0.0
    score_type: str = ""
    seed_smiles: str = ""


@dataclass
class BinderDesign:
    """A protein binder designed via RFdiffusion + ProteinMPNN."""

    backbone_pdb: str = ""
    sequences: list[dict] = field(default_factory=list)
    success: bool = False


@dataclass
class ValidationResult:
    """Binding validation of a novel molecule against the target."""

    smiles: str = ""
    confidence: float = 0.0
    iptm_score: float = 0.0
    success: bool = False


@dataclass
class PipelineResults:
    """Aggregated results from a full pipeline run.

    Each attribute corresponds to one pipeline step and is ``None`` until
    that step has been executed.
    """

    target_name: str = ""
    target_sequence: str = ""
    started_at: str = ""
    finished_at: str = ""
    steps_executed: list[str] = field(default_factory=list)

    # Step outputs
    structure: Optional[str] = None
    structure_length: int = 0
    fold_elapsed_ms: float = 0.0

    screening_hits: list[ScreeningHit] = field(default_factory=list)

    docking_poses: list[DockingPose] = field(default_factory=list)

    novel_molecules: list[NovelMolecule] = field(default_factory=list)

    validated_molecules: list[ValidationResult] = field(default_factory=list)

    binder_design: Optional[BinderDesign] = None

    analysis: Optional[str] = None

    errors: list[dict] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Export helpers
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        """Serialize all results to a plain dictionary."""
        return {
            "target_name": self.target_name,
            "target_sequence_length": len(self.target_sequence),
            "started_at": self.started_at,
            "finished_at": self.finished_at,
            "steps_executed": self.steps_executed,
            "structure_available": self.structure is not None,
            "structure_length": self.structure_length,
            "fold_elapsed_ms": self.fold_elapsed_ms,
            "screening_hits": [
                {"drug": h.drug_name, "smiles": h.smiles, "confidence": h.confidence,
                 "ptm": h.ptm_score, "iptm": h.iptm_score}
                for h in self.screening_hits
            ],
            "docking_poses": [
                {"drug": p.drug_name, "smiles": p.smiles, "confidence": p.confidence}
                for p in self.docking_poses
            ],
            "novel_molecules": [
                {"smiles": m.smiles, "score": m.score, "type": m.score_type}
                for m in self.novel_molecules
            ],
            "validated_molecules": [
                {"smiles": v.smiles, "confidence": v.confidence, "iptm": v.iptm_score}
                for v in self.validated_molecules
            ],
            "binder_design": {
                "success": self.binder_design.success,
                "num_sequences": len(self.binder_design.sequences),
            } if self.binder_design else None,
            "analysis": self.analysis,
            "errors": self.errors,
        }

    def to_json(self, indent: int = 2) -> str:
        """Serialize results as a JSON string."""
        return json.dumps(self.to_dict(), indent=indent, default=str)

    def to_report(self) -> str:
        """Generate a human-readable Markdown report."""
        lines: list[str] = []
        lines.append(f"# ResistAI Pipeline Report: {self.target_name}")
        lines.append("")
        lines.append(f"**Sequence length:** {len(self.target_sequence)} aa")
        lines.append(f"**Steps executed:** {', '.join(self.steps_executed)}")
        lines.append(f"**Started:** {self.started_at}")
        lines.append(f"**Finished:** {self.finished_at}")
        lines.append("")

        if self.structure is not None:
            lines.append("## Structure Prediction (ESMFold)")
            lines.append(f"- PDB length: {self.structure_length} characters")
            lines.append(f"- Elapsed: {self.fold_elapsed_ms:.0f} ms")
            lines.append("")

        if self.screening_hits:
            lines.append("## Drug Screening (Boltz-2)")
            lines.append(f"- Hits: {len(self.screening_hits)}")
            lines.append("")
            lines.append("| Rank | Drug | Confidence | iPTM |")
            lines.append("|------|------|-----------|------|")
            for i, h in enumerate(self.screening_hits[:20], 1):
                lines.append(
                    f"| {i} | {h.drug_name} | {h.confidence:.3f} | {h.iptm_score:.3f} |"
                )
            lines.append("")

        if self.docking_poses:
            lines.append("## Molecular Docking (DiffDock)")
            lines.append(f"- Poses generated: {len(self.docking_poses)}")
            lines.append("")
            for i, p in enumerate(self.docking_poses[:10], 1):
                lines.append(f"{i}. **{p.drug_name}** (confidence {p.confidence:.3f})")
            lines.append("")

        if self.novel_molecules:
            lines.append("## Novel Molecules (MolMIM)")
            lines.append(f"- Generated: {len(self.novel_molecules)}")
            lines.append("")
            lines.append("| # | SMILES | Score | Type |")
            lines.append("|---|--------|-------|------|")
            for i, m in enumerate(self.novel_molecules[:20], 1):
                smi = m.smiles[:60] + ("..." if len(m.smiles) > 60 else "")
                lines.append(f"| {i} | `{smi}` | {m.score:.3f} | {m.score_type} |")
            lines.append("")

        if self.validated_molecules:
            lines.append("## Validation (Boltz-2)")
            lines.append(f"- Validated: {len(self.validated_molecules)}")
            lines.append("")
            for i, v in enumerate(self.validated_molecules[:10], 1):
                smi = v.smiles[:50] + ("..." if len(v.smiles) > 50 else "")
                lines.append(f"{i}. `{smi}` -- confidence {v.confidence:.3f}")
            lines.append("")

        if self.binder_design:
            lines.append("## Binder Design (RFdiffusion + ProteinMPNN)")
            lines.append(f"- Success: {self.binder_design.success}")
            lines.append(f"- Designed sequences: {len(self.binder_design.sequences)}")
            lines.append("")

        if self.analysis:
            lines.append("## AI Analysis")
            lines.append(self.analysis)
            lines.append("")

        if self.errors:
            lines.append("## Errors")
            for err in self.errors:
                lines.append(f"- **{err.get('step', '?')}**: {err.get('error', '?')}")
            lines.append("")

        return "\n".join(lines)

    def __repr__(self) -> str:
        parts = [f"PipelineResults(target={self.target_name!r}"]
        parts.append(f"steps={self.steps_executed}")
        if self.screening_hits:
            parts.append(f"hits={len(self.screening_hits)}")
        if self.novel_molecules:
            parts.append(f"novel={len(self.novel_molecules)}")
        return ", ".join(parts) + ")"
