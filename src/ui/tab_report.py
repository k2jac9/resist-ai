"""Tab: Report — full discovery report with regulatory pathway."""
from __future__ import annotations
import json

from src.ui.common import (
    PATHOGENS, _COMPOUNDS, TARGET_DETAILS,
    _mode_badge, get_demo_targets, _demo_candidates_to_display,
)


def generate_report(label: str, max_n: int, demo: bool) -> tuple[str, str]:
    from datetime import datetime
    info = PATHOGENS[label]
    n = min(max_n, len(_COMPOUNDS))
    targets = get_demo_targets(info["key"])
    candidates = _demo_candidates_to_display(info["key"], n)
    top = candidates[0] if candidates else {}

    rows = "\n".join(
        f"| {c['Rank']} | {c['💊 Drug']} | {c['Binding']} | {c['Safety']} | {c['Overall']} |"
        for c in candidates)

    tech_rows = "\n".join(
        f"| {c['💊 Drug']} | `{next((x[1] for x in _COMPOUNDS if x[0]==c['💊 Drug']), '?')[:45]}` | "
        f"{next((x[4] for x in _COMPOUNDS if x[0]==c['💊 Drug']), '?')[:70]} |"
        for c in candidates)

    report = f"""
{_mode_badge(demo)}

# AMR-AI Discovery Report

**Date:** {datetime.now().strftime("%B %d, %Y")} | **Pathogen:** {label} {info['icon']} | **Mode:** {"Demo (simulated data)" if demo else "Live (Nebius AI Studio)"}

---

## Executive Summary

> {info['plain']}

Our AI screened **{len(candidates)} existing drugs** and identified candidates that could treat
{label} infections. Because these drugs already have established safety profiles,
they can reach patients via the **505(b)(2) pathway in 3-5 years** — vs. 10-15 years for new drugs.

## Top Candidates

| Rank | Drug | Binding | Safety | Overall |
|------|------|---------|--------|---------|
{rows}

## Regulatory Pathway

| Phase | Timeline | Cost |
|-------|----------|------|
| Pre-IND (lab validation) | 6-12 months | $2-5M |
| IND + Phase I (safety) | 12-18 months | $10-20M |
| Phase II (efficacy) | 18-24 months | $30-50M |
| NDA / LPAD submission | 6-12 months | $5-10M |
| **Total** | **3-5 years** | **~$50-100M** |

### Regulatory Enablers
- **FDA Modernization Act 2.0** — in-silico evidence accepted
- **FDA NAMs Roadmap (2025)** — computational toxicology is valid
- **LPAD Pathway** — streamlined approval for serious infections
- **Health Canada GMLP** — aligned AI/ML principles

<details>
<summary style="color:#00C4B4;cursor:pointer">🔬 Technical Report</summary>

### Compound Details
| Drug | SMILES | Mechanism |
|------|--------|-----------|
{tech_rows}

### Target Protein Details
| Target | PDB | Class | Key Resistance Mechanism |
|--------|-----|-------|-------------------------|
{"".join(f"| {t['🎯 Target']} | {TARGET_DETAILS.get(t['🎯 Target'],{}).get('pdb','—')} | {TARGET_DETAILS.get(t['🎯 Target'],{}).get('class','—')} | {TARGET_DETAILS.get(t['🎯 Target'],{}).get('mechanism','—')[:80]} |{chr(10)}" for t in targets)}

### Model Stack
- **Evo2-40B**: StripedHyena 2 arch, single-nucleotide resolution, available via Nebius NIM
- **ESM-2 650M**: Transformer protein LM, 1280-dim per-residue embeddings, HuggingFace
- **Boltz-2**: Diffusion co-folding + affinity, YAML input, MIT license, Nebius NIM
- **ADMET**: RDKit descriptors + SMARTS toxicophore screening (10 structural alerts)
- **Off-target**: Tanimoto similarity (Morgan FP) against 20 critical human anti-targets
- **Scoring**: overall = 0.5 × binding_affinity + 0.3 × safety_score + 0.2 × confidence

### Infrastructure
- Compute: Nebius AI Studio ($100 credits), NVIDIA BioNeMo NIM
- GPU: L40S (48GB VRAM), ~40-60s per Boltz-2 prediction
- Throughput: ~1,000 predictions/hour on 16 GPUs

</details>

---
*Generated by AMR-AI | Evolved 25 Hackathon — Toronto*
"""

    export = json.dumps({"pathogen": info["key"], "targets": targets,
                         "candidates": candidates,
                         "timestamp": datetime.now().isoformat()},
                        indent=2, default=str)
    return report, export
